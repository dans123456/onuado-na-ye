// Helper functions for LocalStorage persistence
const getStoredMembers = () => {
  const saved = localStorage.getItem('ony_members');
  return saved ? JSON.parse(saved) : INITIAL_MEMBERS;
};

const getStoredContributions = () => {
  const saved = localStorage.getItem('ony_contributions');
  return saved ? JSON.parse(saved) : INITIAL_CONTRIBUTIONS;
};

export const getMembers = () => getStoredMembers();

export const getContributions = () => getStoredContributions();

export const saveMembers = (members) => {
  localStorage.setItem('ony_members', JSON.stringify(members));
};

export const saveContributions = (contributions) => {
  localStorage.setItem('ony_contributions', JSON.stringify(contributions));
};

export const updateMemberProfile = (memberId, updatedFields) => {
  const members = getStoredMembers();
  const updated = members.map(m => m.id === memberId ? { ...m, ...updatedFields } : m);
  saveMembers(updated);
  return updated;
};

export const addContribution = (newEntry) => {
  const contributions = getStoredContributions();
  const entryWithId = {
    id: Date.now(),
    ...newEntry,
    payment_date: newEntry.payment_date || new Date().toISOString().split('T')[0]
  };
  const updated = [entryWithId, ...contributions];
  saveContributions(updated);
  return updated;
};

export const bulkAddContributions = (newEntries) => {
  const contributions = getStoredContributions();
  const entriesWithIds = newEntries.map((entry, index) => ({
    id: Date.now() + index,
    ...entry,
    payment_date: entry.payment_date || new Date().toISOString().split('T')[0]
  }));
  const updated = [...entriesWithIds, ...contributions];
  saveContributions(updated);
  return updated;
};
